namespace Clavus.Shared.Abstractions.Domain;

/// <summary>
/// Base class of every class that represents a database table. Provides the control fields shared by
/// all business tables: numeric key, public identifier, creation and last update dates and active flag.
/// </summary>
/// <remarks>
/// <para>
/// Module DbContexts derived from <c>ModuleDbContext</c> configure these fields by convention (identity
/// key, unique identifier, database defaults) and fill <see cref="CreateIn"/> and <see cref="UpdateIn"/>
/// on <c>SaveChanges</c>. The module does not need to configure them.
/// </para>
/// <para>
/// Bulk operations (<c>ExecuteUpdate</c>/<c>ExecuteDelete</c>) do not go through <c>SaveChanges</c>, so
/// they do not update <see cref="UpdateIn"/>: set it in the update expression itself.
/// </para>
/// </remarks>
public abstract class Entity
{
    /// <summary>
    /// Primary key, generated by the database as identity
    /// </summary>
    public long Id { get; private set; }

    /// <summary>
    /// Public identifier (UUID version 7), generated when the entity is created and unique in the table
    /// </summary>
    public Guid Identifier { get; private set; } = Guid.CreateVersion7();

    /// <summary>
    /// Local date and time when the entity was inserted. Never changes after the insert.
    /// </summary>
    public DateTime CreateIn { get; private set; }

    /// <summary>
    /// Local date and time of the last change to the entity, updated on every save with changes
    /// </summary>
    public DateTime UpdateIn { get; private set; }

    /// <summary>
    /// Indicates whether the record is active. Default <see langword="true"/>.
    /// </summary>
    public bool IsActive { get; set; } = true;
}
